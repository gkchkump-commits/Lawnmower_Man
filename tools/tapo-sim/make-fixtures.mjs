#!/usr/bin/env node
// Render the simulator's video fixtures (contract §11.3). Needs ffmpeg with libx264; the outputs
// are committed, so tests, the simulator and CI never need ffmpeg. Run through make-fixtures.sh.
//
//   tests/fixtures/tapo/sim/stream1/p{i}_t{j}.h264         640x360, i = -4..4, j = -2..2
//   tests/fixtures/tapo/sim/stream1/p{i}_t{j}_person.h264  the same with a green walking figure (|i|,|j| <= 1)
//   tests/fixtures/tapo/sim/stream1/privacy.h264           "Privacy Mode is on" placeholder
//   tests/fixtures/tapo/sim/stream2/…                      the same at 320x180
//   tests/fixtures/tapo/sim/manifest.json                  geometry, frame counts, sizes, SHA-256
//   tests/fixtures/tapo/bframes.mp4                        2 s with B-frames, one moof per frame
//   tests/fixtures/tapo/bframes-gop.mp4                    the same, one moof per GOP (multi-sample trun)
//
// Every segment is one 1-second GOP (15 frames at 15 fps, IDR first), one slice per frame, an
// access unit delimiter (AUD) before every frame and SPS/PPS before every IDR. All segments of a
// stream are encoded with identical settings (x264 `stitchable`), so their SPS/PPS are byte-for-
// byte the same and the simulator can switch between them at any IDR without a decoder reset.
// The panorama is a Mandelbrot "seahorse valley" (ffmpeg's own lavfi source, no third-party
// image), desaturated so that nothing but the figure is green.
//
// go2rtc-sample.mp4 is captured separately (needs the go2rtc binary): capture-go2rtc-sample.mjs.
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  FPS, GOP_FRAMES, PANO, SUB_VIEW, VIEW, SIM_TRUTH,
  PAN_STEP_PX, PAN_STEP_UNITS, TILT_STEP_PX, TILT_STEP_UNITS, PAN_STEPS, TILT_STEPS, PERSON_STEPS,
  PERSON, allCells, cropOrigin, personCells, segmentId,
} from './geometry.mjs';
import { accessUnits, nalType, parameterSets, splitAnnexB } from './h264.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const outDir = path.join(root, 'tests/fixtures/tapo');
const simDir = path.join(outDir, 'sim');
const FONT = ['/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', '/usr/share/fonts/TTF/DejaVuSans.ttf', '/Library/Fonts/Arial.ttf', 'C:/Windows/Fonts/arial.ttf'].find((f) => fs.existsSync(f));

/** @param {string[]} args */
function ffmpeg(args) {
  const r = spawnSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', ...args], { encoding: 'utf8' });
  if (r.error) throw new Error(`ffmpeg not found (${r.error.message}); install ffmpeg with libx264`);
  if (r.status !== 0) throw new Error(`ffmpeg failed: ${r.stderr}\nargs: ${args.join(' ')}`);
}

// Same flags as contract §11.3, plus: stitchable (identical PPS in every file), one thread
// (deterministic output) and the x264 version SEI removed (it differs between machines).
const X264 = [
  '-c:v', 'libx264', '-profile:v', 'high', '-level', '3.1', '-pix_fmt', 'yuv420p',
  '-r', String(FPS), '-g', String(GOP_FRAMES), '-keyint_min', String(GOP_FRAMES), '-sc_threshold', '0', '-bf', '0',
  '-threads', '1', '-x264-params', 'sliced-threads=0:slices=1:repeat-headers=1:stitchable=1',
];
const ANNEXB = ['-bsf:v', 'filter_units=remove_types=6,h264_metadata=aud=insert', '-f', 'h264'];

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tapo-sim-fixtures-'));
const pano = path.join(tmp, 'pano.png');
try {
  console.log(`panorama ${PANO.width}x${PANO.height} …`);
  ffmpeg([
    '-f', 'lavfi', '-i',
    `mandelbrot=s=${PANO.width}x${PANO.height}:start_x=-0.743643887037151:start_y=0.13182590420533:start_scale=0.0004:end_scale=0.0004:maxiter=1024:outer=normalized_iteration_count:inner=period`,
    '-frames:v', '1',
    // grey-blue, slightly softened (the per-pixel speckle of the fractal costs bits and says
    // nothing at the 64x36 / 128x72 scale the worker analyses)
    '-vf', 'gblur=sigma=1.1,hue=s=0,colorchannelmixer=rr=0.82:gg=0.9:bb=1.0:bg=0.06,eq=contrast=1.2:brightness=-0.03',
    pano,
  ]);

  // The figure as a transparent RGBA image; `overlay` moves it per frame (drawbox positions are
  // evaluated only once).
  const figurePng = path.join(tmp, 'figure.png');
  ffmpeg([
    '-f', 'lavfi', '-i', `color=c=black@0.0:s=${PERSON.width}x${PERSON.height},format=rgba`, '-frames:v', '1',
    '-vf', PERSON.boxes.map((b) => `drawbox=x=${b.x}:y=${b.y}:w=${b.w}:h=${b.h}:color=0x00FF00@1.0:t=fill:replace=1`).join(','),
    figurePng,
  ]);
  /** @type {Record<string, any>} */
  const manifest = {
    v: 1,
    note: 'Generated by tools/tapo-sim/make-fixtures.sh; see tools/tapo-sim/README.md.',
    fps: FPS,
    gopFrames: GOP_FRAMES,
    panorama: { ...PANO, source: 'ffmpeg lavfi mandelbrot (seahorse valley), desaturated' },
    grid: { panSteps: PAN_STEPS, tiltSteps: TILT_STEPS, panStepUnits: PAN_STEP_UNITS, tiltStepUnits: TILT_STEP_UNITS, panStepPx: PAN_STEP_PX, tiltStepPx: TILT_STEP_PX, personSteps: PERSON_STEPS },
    truth: SIM_TRUTH,
    streams: {},
  };

  for (const [stream, size, crf] of /** @type {const} */ ([['stream1', VIEW, 30], ['stream2', SUB_VIEW, 30]])) {
    const dir = path.join(simDir, stream);
    fs.rmSync(dir, { recursive: true, force: true });
    fs.mkdirSync(dir, { recursive: true });
    const scale = size.width === VIEW.width ? '' : `,scale=${size.width}:${size.height}:flags=area`;
    /** @type {Array<{ id: string, filter: string, input: string[] }>} */
    const jobs = [];
    const still = ['-loop', '1', '-framerate', String(FPS), '-i', pano];
    for (const { i, j } of allCells()) {
      const { x, y } = cropOrigin(i, j);
      jobs.push({ id: segmentId(i, j), input: still, filter: `crop=${VIEW.width}:${VIEW.height}:${x}:${y}${scale},format=yuv420p` });
    }
    const walker = [...still, '-loop', '1', '-framerate', String(FPS), '-i', figurePng];
    for (const { i, j } of personCells()) {
      const { x, y } = cropOrigin(i, j);
      jobs.push({
        id: segmentId(i, j, true),
        input: walker,
        filter: `[0:v][1:v]overlay=x='${PERSON.x}+${PERSON.pxPerSec}*t':y=${PERSON.y}:eval=frame,crop=${VIEW.width}:${VIEW.height}:${x}:${y}${scale},format=yuv420p`,
      });
    }
    const text = FONT
      ? `,drawtext=fontfile='${FONT}':text='Privacy Mode is on':fontcolor=0xD8DEE6:fontsize=${Math.round(size.height / 12)}:x=(w-text_w)/2:y=(h-text_h)/2`
      : '';
    jobs.push({
      id: 'privacy',
      input: ['-f', 'lavfi', '-i', `color=c=0x15191F:s=${size.width}x${size.height}:r=${FPS}`],
      filter: `drawbox=x=iw/2-ih/16:y=ih/2-ih/4:w=ih/8:h=ih/10:color=0x5A6470:t=fill${text},format=yuv420p`,
    });

    /** @type {Record<string, any>} */
    const segs = {};
    /** @type {string|null} */
    let params = null;
    for (const job of jobs) {
      const file = path.join(dir, `${job.id}.h264`);
      ffmpeg([...job.input, '-frames:v', String(GOP_FRAMES), '-filter_complex', job.filter, ...X264, '-crf', String(crf), ...ANNEXB, file]);
      const data = fs.readFileSync(file);
      const aus = accessUnits(splitAnnexB(data));
      if (aus.length !== GOP_FRAMES) throw new Error(`${stream}/${job.id}: ${aus.length} frames, expected ${GOP_FRAMES}`);
      const types = aus.map((au) => au.map(nalType));
      if (!types[0].includes(5) || types.slice(1).some((t) => t.includes(5))) throw new Error(`${stream}/${job.id}: the IDR must be the first and only keyframe`);
      if (types.some((t) => t[0] !== 9 || t.filter((n) => n === 1 || n === 5).length !== 1)) throw new Error(`${stream}/${job.id}: every frame needs an AUD and exactly one slice`);
      const ps = parameterSets(aus[0]);
      const key = `${ps.sps.toString('hex')}/${ps.pps.toString('hex')}`;
      if (params === null) params = key;
      else if (params !== key) throw new Error(`${stream}/${job.id}: SPS/PPS differ from the other segments`);
      segs[job.id] = { frames: aus.length, bytes: data.length, sha256: crypto.createHash('sha256').update(data).digest('hex') };
    }
    manifest.streams[stream] = { width: size.width, height: size.height, segments: segs };
    const total = Object.values(segs).reduce((n, s) => n + s.bytes, 0);
    console.log(`${stream}: ${jobs.length} segments, ${(total / 1024).toFixed(0)} KB`);
  }
  fs.writeFileSync(path.join(simDir, 'manifest.json'), `${JSON.stringify(manifest, null, 1)}\n`);

  // fMP4 parser fixtures (lane A's fmp4.js): B-frames, so pts != dts (composition offsets).
  const bf = ['-f', 'lavfi', '-i', `testsrc2=size=320x180:rate=${FPS}:duration=2`, '-c:v', 'libx264', '-profile:v', 'high', '-pix_fmt', 'yuv420p',
    '-g', String(GOP_FRAMES), '-keyint_min', String(GOP_FRAMES), '-sc_threshold', '0', '-bf', '2', '-threads', '1', '-crf', '32'];
  ffmpeg([...bf, '-movflags', 'frag_every_frame+empty_moov+default_base_moof', '-f', 'mp4', path.join(outDir, 'bframes.mp4')]);
  ffmpeg([...bf, '-movflags', 'frag_keyframe+empty_moov+default_base_moof', '-f', 'mp4', path.join(outDir, 'bframes-gop.mp4')]);
  for (const f of ['bframes.mp4', 'bframes-gop.mp4']) console.log(`${f}: ${fs.statSync(path.join(outDir, f)).size} B`);
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
